"""Gate for every grid training job: exit 0 only if the grid data of the named dimensions were
generated by experiments/gen_data_grid.py with every reference fingerprint matching
results/data_manifest_grid.json, and every stored file still has the SHA-256 recorded at
generation (results/datagen_grid/manifest_full_d<d>.json). Prints "DATA MISMATCH" and exits 1
otherwise. Reference rows may match strictly (SHA-256) or within tolerance
(experiments/gen_data_grid.py, tools/check_manifest_tol.py pattern). Usage: python tools/check_grid_data.py 2 [3] [--quick]  (--quick: skip re-hashing
the large field files, check only the reference rows)."""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import numpy as np                                     # noqa: E402

from pfm2d import data as D                            # noqa: E402
sys.path.insert(0, str(ROOT / "experiments"))
import gen_data_grid as G                              # noqa: E402


OWN = ("fields.npy", "chan.npy", "bc.npy", "meta.json")


def sha_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 22), b""):
            h.update(b)
    return h.hexdigest()


def main(argv):
    quick = "--quick" in argv
    dims = [int(a) for a in argv if a.isdigit()] or [2, 3]
    for dim in dims:
        if (ROOT / f"results/datagen_grid/MISMATCH_d{dim}.json").exists():
            print(f"DATA MISMATCH: results/datagen_grid/MISMATCH_d{dim}.json exists")
            return 1
    ref = json.loads((ROOT / "results/data_manifest_grid.json").read_text())["reference"]
    bad, n, kinds = [], 0, {}
    for dim in dims:
        fp = ROOT / f"results/datagen_grid/manifest_full_d{dim}.json"
        if not fp.exists():
            print(f"DATA MISMATCH: {fp.name} missing (grid data for d = {dim} not generated)")
            return 1
        full = json.loads(fp.read_text())
        for name, rec in full["systems"].items():
            d_out = D.system_dir(name, dim)
            for split, info in rec["splits"].items():
                if not info.get("reference_match"):
                    bad.append(f"d{dim}/{name}/{split}: reference")
                    continue
                r = ref[f"d{dim}/{name}/{split}"]
                f = np.load(d_out / f"{split}_fields.npy", mmap_mode="r")
                ch = np.load(d_out / f"{split}_chan.npy")
                c = G.compare(np.asarray(f[:r["rows"]]), ch[:r["rows"]], r)
                kinds[c["match"]] = kinds.get(c["match"], 0) + 1
                if not c["match"]:
                    bad.append(f"d{dim}/{name}/{split}: reference rows")
                if not quick:
                    # only the split's own four files: the generation job's record of split
                    # "test" also listed test_bc_* files caught half-written by a parallel worker
                    # (glob "test_*"; fixed in gen_data_grid.py 21 Oct 2026, 17:10 PDT); those
                    # files are checked under their own split
                    own = {f"{split}_{x}" for x in OWN}
                    for fn, h in info["files"].items():
                        if fn not in own:
                            continue
                        n += 1
                        if sha_file(d_out / fn) != h:
                            bad.append(f"d{dim}/{name}/{fn}")
    if bad:
        print("DATA MISMATCH", bad[:10])
        return 1
    print(f"grid data OK for d = {dims}; {n} files re-hashed; reference rows match {kinds}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
